import { readFileSync, writeFileSync } from "node:fs";
import { format } from "prettier";
const source = "crates/tauri-plugin-jj-store/schema.json";
const document = JSON.parse(readFileSync(source, "utf8"));
const allowed = new Set([
  "$ref",
  "type",
  "properties",
  "required",
  "additionalProperties",
  "patternProperties",
  "items",
  "prefixItems",
  "minItems",
  "maxItems",
  "minimum",
  "maximum",
  "minLength",
  "maxLength",
  "pattern",
  "format",
  "enum",
  "const",
  "oneOf",
  "anyOf",
  "title",
  "description",
  "default",
]);
function type(schema) {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  for (const key of Object.keys(schema))
    if (!allowed.has(key))
      throw Error(`Unsupported history schema keyword ${key}`);
  if (schema.$ref) {
    const name = schema.$ref.replace("#/$defs/", "");
    if (!document.$defs[name]) throw Error("Nonlocal schema reference");
    return name;
  }
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  const alternatives = schema.oneOf ?? schema.anyOf;
  if (alternatives) return alternatives.map((s) => `(${type(s)})`).join(" | ");
  if (Array.isArray(schema.type))
    return schema.type.map((t) => type({ ...schema, type: t })).join(" | ");
  switch (schema.type) {
    case "null":
      return "null";
    case "boolean":
      return "boolean";
    case "integer":
      return ["uint64", "int64", "uint"].includes(schema.format)
        ? "number | bigint"
        : "number";
    case "string":
      return "string";
    case "array":
      if (schema.prefixItems) {
        if (
          schema.minItems !== schema.prefixItems.length ||
          schema.maxItems !== schema.prefixItems.length
        )
          throw Error("Unsupported open tuple");
        return `[${schema.prefixItems.map(type).join(",")}]`;
      }
      return `Array<${type(schema.items ?? true)}>`;
    case "object": {
      const properties = Object.entries(schema.properties ?? {});
      const patterns = Object.values(schema.patternProperties ?? {});
      if (!properties.length)
        return `Record<string,${type(patterns[0] ?? schema.additionalProperties ?? true)}>`;
      if (
        patterns.length ||
        (schema.additionalProperties && schema.additionalProperties !== true)
      )
        throw Error("Unsupported mixed record");
      return `{${properties.map(([key, s]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}:${type(s)}`).join(";")}}`;
    }
    default:
      throw Error(`Unsupported history schema type ${schema.type}`);
  }
}
const { $schema, $defs, ...root } = document;
const artifacts = new Map([
  [
    "packages/jj-history/src/generated.ts",
    await format(
      "// Generated by scripts/history-contracts.mjs from owned Rust schema.\n" +
        Object.entries(document.$defs)
          .map(([name, s]) => `export type ${name} = ${type(s)};`)
          .join("\n") +
        `\nexport type Contract = ${type(root)};`,
      { parser: "typescript" },
    ),
  ],
  [
    "packages/jj-history/src/schema.json",
    await format(JSON.stringify(document), { parser: "json" }),
  ],
]);
for (const [path, text] of artifacts) {
  if (process.argv[2] === "--write") writeFileSync(path, text);
  else if (process.argv[2] === "--check") {
    if (readFileSync(path, "utf8") !== text)
      throw Error(`Generated history contract drift: ${path}`);
  } else throw Error("Use --write or --check");
}
console.log("History client contracts match owned native schema.");
